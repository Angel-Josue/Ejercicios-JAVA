    private void btnCargardatosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargardatosActionPerformed
        // TODO add your handling code here:
        try {
        File archivo = new File(rutaArchivo);
        Scanner sc = new Scanner(archivo);
        indice = 0;

        while (sc.hasNextLine() && indice < temperaturas.length) {
            String linea = sc.nextLine().trim();
            if (!linea.isEmpty()) {
                temperaturas[indice] = Double.parseDouble(linea);
                indice++;
            }
        }
        sc.close();

        JOptionPane.showMessageDialog(this, "Datos cargados.");
    } catch (FileNotFoundException e) {
        JOptionPane.showMessageDialog(this, "No se encontró temp/temperaturas.txt");
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El archivo tiene un valor que no es número.");
    }

    }//GEN-LAST:event_btnCargardatosActionPerformed

    private void btnEstadisticasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEstadisticasActionPerformed
        // TODO add your handling code here:
         if (indice < 6) {
        JOptionPane.showMessageDialog(this, "Primero presiona Cargar Datos.");
        return;
    }

    double suma = 0;
    int calidos = 0;
    int frescos = 0;

    for (int i = 0; i < temperaturas.length; i++) {
        suma = suma + temperaturas[i];
        if (temperaturas[i] >= 25.0) {
            calidos++;
        } else {
            frescos++;
        }
    }

    double promedio = suma / temperaturas.length;

    taResultados.setText("Análisis Climático\n"
            + "------------------\n"
            + "Promedio de Temperatura: " + promedio + "\n"
            + "Días Cálidos (>= 25°): " + calidos + "\n"
            + "Días Frescos (< 25°): " + frescos);

    }//GEN-LAST:event_btnEstadisticasActionPerformed


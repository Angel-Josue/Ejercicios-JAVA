    private void btnAgregartaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregartaActionPerformed
        // TODO add your handling code here:
        if (indice >= 5){
        JOptionPane.showMessageDialog(this, "Ya ingresaste las 5 tareas.");
        return;   
        }
        
        String tarea = txtTarea.getText().trim(); //el trim sirve para quitar los espacios al inicio y al final
        
        if (tarea.isEmpty()){
        JOptionPane.showMessageDialog(this, "Escribe una Tarea");
        return;
        }
        
        tareas [indice] = tarea;
        indice++;
        taListado.append(indice + ". " + tarea + "\n");
        txtTarea.setText("");
        txtTarea.requestFocus();
    }//GEN-LAST:event_btnAgregartaActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        // TODO add your handling code here:
        if (indice < 5) {
        JOptionPane.showMessageDialog(this, "Faltan tareas. Llevas " + indice + " de 5.");
        return;
    }
        
       if (indice < 5) {
        JOptionPane.showMessageDialog(this, "Faltan tareas. Llevas " + indice + " de 5.");
        return;
    }
//JOptionPane.showMessageDialog<<<<< es la responsable de que el cuadrito aparezca :)
    try {
        File carpeta = new File("temp");
        if (!carpeta.exists()) {
            carpeta.mkdir();
        }

        File archivo = new File(carpeta, "angel_agenda.txt");

        PrintWriter pw = new PrintWriter(new FileWriter(archivo));
        pw.println("Agenda de Tareas");
        for (int i = 0; i < tareas.length; i++) {
            pw.println((i + 1) + ". " + tareas[i]);
        }
        pw.close();

        JOptionPane.showMessageDialog(this, "Agenda exportada en la carpeta temp.");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al escribir el archivo.");
    }
    }//GEN-LAST:event_btnExportarActionPerformed


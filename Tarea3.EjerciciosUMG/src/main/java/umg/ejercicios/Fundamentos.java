    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // TODO add your handling code here:
        try {
        String nombre = txtNombre.getText().trim();
        String pais = txtPais.getText().trim();
        int oyentes = Integer.parseInt(txtOyentes.getText().trim());

        if (nombre.isEmpty() || pais.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Completa el nombre y el país.");
            return;
        }

        Artista a = new Artista();
        a.nombre = nombre;
        a.paisOrigen = pais;
        a.oyentesMensuales = oyentes;

         taResultados.append("ARTISTA CREADO/A \n");
         taResultados.append("  Nombre: " + a.nombre + "\n");
         taResultados.append("  País: " + a.paisOrigen + "\n");
         taResultados.append("  Oyentes mensuales: " + a.oyentesMensuales + "\n\n");

        File carpeta = new File("temp");
        if (!carpeta.exists()) {
            carpeta.mkdir();
        }
        PrintWriter pw = new PrintWriter(new FileWriter(new File(carpeta, "artistasEJ5.txt"), true));
        pw.println(a.nombre + "," + a.paisOrigen + "," + a.oyentesMensuales);
        pw.close();

        txtNombre.setText("");
        txtPais.setText("");
        txtOyentes.setText("");
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Los oyentes deben ser un número entero.");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al escribir el archivo de artistas.");
    }


    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
        // TODO add your handling code here:
        try {
        String titulo = txtTitulo.getText().trim();
        String interprete = txtInterprete.getText().trim();
        int duracion = Integer.parseInt(txtDuracion.getText().trim());
        String genero = txtGenero.getText().trim();

        if (titulo.isEmpty() || interprete.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Completa el título y el artista.");
            return;
        }

        Cancion c = new Cancion();
        c.titulo = titulo;
        c.nombreArtista = interprete;
        c.duracionSegundos = duracion;
        c.genero = genero;

        taResultados.append("CANCIÓN CREADA\n");
        taResultados.append("  Título: " + c.titulo + "\n");
        taResultados.append("  Artista: " + c.nombreArtista + "\n");
        taResultados.append("  Duración: " + c.duracionSegundos + " segundos\n");
        taResultados.append("  Género: " + c.genero + "\n\n");

        File carpeta = new File("temp");
        if (!carpeta.exists()) {
            carpeta.mkdir();
        }
        PrintWriter pw = new PrintWriter(new FileWriter(new File(carpeta, "cancionesEJ5.txt"), true));
        pw.println(c.titulo + "," + c.nombreArtista + "," + c.duracionSegundos + "," + c.genero);
        pw.close();

        txtTitulo.setText("");
        txtInterprete.setText("");
        txtDuracion.setText("");
        txtGenero.setText("");
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La duración debe ser un número entero (segundos).");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al escribir el archivo de canciones.");
    }


    }//GEN-LAST:event_btnCrearCancionActionPerformed


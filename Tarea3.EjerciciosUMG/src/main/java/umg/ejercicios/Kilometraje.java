    private void btnAggrutaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAggrutaActionPerformed
        // TODO add your handling code here:
        if (indice >= 7){
            JOptionPane.showMessageDialog (this, "Ya ingresaste los 7 recorridos.");
            return;
        }
        
        try {
            double km = Double.parseDouble(txtKilometraje.getText());
            rutas[indice] = km;
            indice++;
            txtKilometraje.setText(" ");
            txtKilometraje.requestFocus();
            JOptionPane.showMessageDialog (this, " ruta " + indice + " de 7 agregada.");
           } catch (NumberFormatException e) {
               JOptionPane.showMessageDialog (this, "Ingrese un numero valido.");
           }
    }//GEN-LAST:event_btnAggrutaActionPerformed

    private void btnGenreportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenreportActionPerformed
        // TODO add your handling code here:
        if (indice < 7){
         JOptionPane.showMessageDialog (this, "faltan rutas. Llevas " + indice + " de 7.");
         return;
        }
        
        double  total = 0;
        for (int i = 0; i < rutas.length; i++){
            total = total + rutas [i];
            
        }
        
        double promedio  = total / 7;
        
        try {
            File carpeta = new File ("temp");
            if (!carpeta.exists()){
            carpeta.mkdir();
            
            }
            
            File archivo = new  File (carpeta, "Angel_reporte_rutas.txt");
            
            PrintWriter pw = new PrintWriter (new FileWriter (archivo));
            pw.println("Reporte semanal de rutas");
            pw.println("total de Kilometro: " + total);
            pw.println("Promedio Diario: " + promedio);
            pw.close();
            
             JOptionPane.showMessageDialog(this, "Reporte generado en la carpeta temp.");
            
        } catch (IOException e){
             JOptionPane.showMessageDialog(this, "Error al escribir el archivo.");
        }
       
    }//GEN-LAST:event_btnGenreportActionPerformed


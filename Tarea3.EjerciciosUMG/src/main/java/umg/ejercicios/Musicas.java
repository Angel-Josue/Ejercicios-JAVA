private void cargarDatos() {
    try {
        File archivo = new File("temp", "discos.csv");
        Scanner sc = new Scanner(archivo);
        int i = 0;

        while (sc.hasNextLine() && i < 5) {
            String linea = sc.nextLine();
            String[] partes = linea.split(",");
            titulos[i] = partes[0].trim();
            anios[i] = Integer.parseInt(partes[1].trim());
            i++;
        }
        sc.close();
    } catch (FileNotFoundException e) {
        JOptionPane.showMessageDialog(this, "No se encontró temp/discos.csv");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "El archivo discos.csv tiene un formato incorrecto.");
    }
}
    


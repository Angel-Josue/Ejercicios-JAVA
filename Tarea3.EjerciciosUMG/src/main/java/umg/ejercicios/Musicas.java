    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
String buscado = txtBuscar.getText().trim();
    boolean encontrado = false;

    for (int i = 0; i < titulos.length; i++) {
        if (buscado.equalsIgnoreCase(titulos[i])) {
            lblAnio.setText("Año: " + anios[i]);
            encontrado = true;
            break;
        }
    }

    if (!encontrado) {
        lblAnio.setText("Álbum no encontrado");
    }

    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnRegistroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistroActionPerformed
        // TODO add your handling code here:
        String buscado = txtBuscar.getText().trim();
    int posicion = -1;

    for (int i = 0; i < titulos.length; i++) {
        if (buscado.equalsIgnoreCase(titulos[i])) {
            posicion = i;
            break;
        }
    }

    if (posicion == -1) {
        JOptionPane.showMessageDialog(this, "Álbum no encontrado.");
        return;
    }

    try {
        int Nuevoaño = Integer.parseInt(txtNuevoaño.getText().trim());
        anios[posicion] = Nuevoaño;

        File archivo = new File("temp", "discos.csv");
        PrintWriter pw = new PrintWriter(new FileWriter(archivo, false));
        for (int i = 0; i < titulos.length; i++) {
            pw.println(titulos[i] + "," + anios[i]);
        }
        pw.close();

        lblAnio.setText("Año: " + Nuevoaño);
        txtNuevoaño.setText("");
        JOptionPane.showMessageDialog(this, "Registro actualizado.");
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El año debe ser un número entero.");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al escribir el archivo.");
    }

    }//GEN-LAST:event_btnRegistroActionPerformed


    private void btnCatalogoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCatalogoActionPerformed
        // TODO add your handling code here:
        
     taInventario.setText("");

    for (int i = 0; i < catalogo.size(); i++) {
        Videojuegos v = catalogo.get(i);
         taInventario.append((i + 1) + ". " + v.titulo + " | " + v.consola + " | " + v.añoLanzamiento + "\n");
    }

    taInventario.append("\nTotal de juegos: " + catalogo.size());

    }//GEN-LAST:event_btnCatalogoActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
         try {
        String titulo = txtTitulo.getText().trim();
        String consola = txtConsola.getText().trim();
        int año = Integer.parseInt(txtLanzamiento.getText().trim());

        if (titulo.isEmpty() || consola.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Completa el título y la consola.");
            return;
        }

        Videojuegos v = new Videojuegos(titulo, consola, año);
        catalogo.add(v);

        txtTitulo.setText("");
        txtConsola.setText("");
        txtLanzamiento.setText("");
        txtTitulo.requestFocus();
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El año debe ser un número entero.");
    }

    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
    
    if (catalogo.size() > 0) {
        catalogo.remove(catalogo.size() - 1);
        JOptionPane.showMessageDialog(this, "Último juego eliminado."); //Mensaje que sale en el cuadrito
    } else {
        JOptionPane.showMessageDialog(this, "El catálogo está vacío."); //Mensaje que sale en el cuadrito
    }

    }//GEN-LAST:event_btnEliminarActionPerformed

